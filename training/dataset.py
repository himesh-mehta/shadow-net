"""
PyTorch Dataset for SHADOW-NET Audio Deepfake Detection.
Reuses production preprocessing and feature extraction modules
from backend/app/audio/ to guarantee train/inference feature parity.
"""

import sys
import json
import logging
from pathlib import Path
from typing import Tuple, Dict, Any, Optional

import numpy as np
import torch
from torch.utils.data import Dataset

# Ensure backend modules can be imported directly
_BACKEND_DIR = Path(__file__).resolve().parent.parent / "backend"
if str(_BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(_BACKEND_DIR))

from app.audio.preprocessing import load_audio, normalize_audio
from app.audio.features import extract_mel_spectrogram, TARGET_SR, DEFAULT_WINDOW_SEC

logger = logging.getLogger("shadow_net.training.dataset")


class AudioSpoofDataset(Dataset):
    """
    Dataset that loads audio files from a JSON manifest (generated by dataset_prep.py),
    preprocesses them to 16kHz mono, extracts 2.0-second windows, and generates
    1-channel log-Mel-spectrograms of shape (1, 128, 63).
    """

    def __init__(
        self,
        manifest_path: str,
        target_sec: float = DEFAULT_WINDOW_SEC,
        sr: int = TARGET_SR,
        transform=None,
    ):
        self.manifest_file = Path(manifest_path)
        if not self.manifest_file.is_file():
            raise FileNotFoundError(f"Manifest file not found: {manifest_path}")

        with open(self.manifest_file, "r", encoding="utf-8") as f:
            self.records = json.load(f)

        self.target_sec = target_sec
        self.sr = sr
        self.target_samples = int(target_sec * sr)
        self.transform = transform

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int]:
        record = self.records[idx]
        audio_path = record["audio_path"]
        label = int(record["label"])

        try:
            # 1. Load and resample audio using production preprocessing
            audio, _ = load_audio(audio_path, target_sr=self.sr)

            # 2. Window slice or pad to target length (2.0s = 32,000 samples)
            if len(audio) < self.target_samples:
                padded = np.zeros(self.target_samples, dtype=np.float32)
                padded[:len(audio)] = audio
                audio_slice = padded
            else:
                # Use centered or first window
                audio_slice = audio[:self.target_samples]

            # 3. Extract log-Mel-spectrogram using production pipeline
            # Returns shape: (128, time_frames)
            mel_spec = extract_mel_spectrogram(audio_slice, sr=self.sr)

            # 4. Convert to PyTorch Tensor with channel dimension: (1, 128, time_frames)
            tensor = torch.from_numpy(mel_spec).unsqueeze(0).float()

            if self.transform is not None:
                tensor = self.transform(tensor)

            return tensor, label

        except Exception as e:
            raise RuntimeError(f"Cannot load dataset audio {audio_path}; fix the manifest or file before training.") from e
